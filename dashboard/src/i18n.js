export function t(key, vars = {}) {
  const s = dict[lang.value][key] ?? dict.en[key] ?? key
  return s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] !== undefined ? vars[k] : `{${k}}`))
}

export function featureLabel(feature, fallback) {
  return lang.value === 'ar' ? (featureAr[feature] ?? fallback ?? feature) : (fallback ?? feature)
}

export function toggleLang() {
  lang.value = lang.value === 'en' ? 'ar' : 'en'
}

export const pct = (x, digits = 0) => {
  if (x === null || x === undefined) return '-'
  if (x > 0 && x < 0.01 && digits === 0) return '<1%'
  return `${(x * 100).toFixed(digits)}%`
}
